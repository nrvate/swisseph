#!/usr/bin/env python3
"""Write swenut2000a_sparse.h: the nonzero multipliers of each IAU 2000A term.

swenut2000a.h stores every term's argument as a dense row of multipliers, 5 for
the luni-solar series and 14 for the planetary one; about 3.4 of them are
nonzero. calc_nutation_2000a_derivs() (swephlib.c) builds each term's sine and
cosine as a product of e^(ik x) powers, one factor per nonzero multiplier, and
walking the dense row cost more than the products. The tables are the IAU
2000A standard and do not change, so the sparse form is generated once and
checked in; G32 (tests/nutspeed.c) verifies it against nls[] and npl[].

Run from the repository root:
    python3 tools/gen_nut_sparse.py
"""
import re
import sys

NMAX = 6  # the most nonzero multipliers in any term (planetary; luni-solar 5)


def table(src, name):
    m = re.search(r"static const int16 %s\[\] = \{(.*?)\};" % name, src, re.S)
    if not m:
        sys.exit("gen_nut_sparse: no table %s[] in swenut2000a.h" % name)
    body = re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)
    body = re.sub(r"//[^\n]*", "", body)
    return [int(x) for x in re.findall(r"-?\d+", body)]


def sparse(values, width):
    rows = []
    for i in range(0, len(values), width):
        row = values[i:i + width]
        nz = [(j, k) for j, k in enumerate(row) if k != 0]
        if len(nz) > NMAX:
            sys.exit("gen_nut_sparse: a term has %d nonzero multipliers" % len(nz))
        js = [j for j, _ in nz] + [0] * (NMAX - len(nz))
        ks = [k for _, k in nz] + [0] * (NMAX - len(nz))
        rows.append("  {%d, {%s}, {%s}}" % (len(nz), ", ".join(map(str, js)), ", ".join(map(str, ks))))
    return rows


def main():
    src = open("swenut2000a.h").read()
    nls, npl = table(src, "nls"), table(src, "npl")
    ls, pl = sparse(nls, 5), sparse(npl, 14)
    kls, kpl = max(abs(k) for k in nls), max(abs(k) for k in npl)
    out = [
        "/* swenut2000a_sparse.h -- GENERATED by tools/gen_nut_sparse.py from",
        " * swenut2000a.h; do not edit. Each IAU 2000A term's nonzero argument",
        " * multipliers: n of them, the argument index j and multiplier k of each.",
        " * G32 (tests/nutspeed.c) checks these against nls[] and npl[]. */",
        "#ifndef SWENUT2000A_SPARSE_H",
        "#define SWENUT2000A_SPARSE_H",
        "#define NUT_SPARSE_NMAX %d" % NMAX,
        "/* the largest |multiplier| in each series: the power tables' half-width */",
        "#define NUT_LS_KMAX %d" % kls,
        "#define NUT_PL_KMAX %d" % kpl,
        "struct nut_sparse {",
        "  unsigned char n;",
        "  unsigned char j[NUT_SPARSE_NMAX];",
        "  signed char k[NUT_SPARSE_NMAX];",
        "};",
        "static const struct nut_sparse nut_ls_sparse[%d] = {" % len(ls),
        ",\n".join(ls),
        "};",
        "static const struct nut_sparse nut_pl_sparse[%d] = {" % len(pl),
        ",\n".join(pl),
        "};",
        "#endif",
        "",
    ]
    open("swenut2000a_sparse.h", "w").write("\n".join(out))
    print("swenut2000a_sparse.h: %d luni-solar, %d planetary terms" % (len(ls), len(pl)))


main()
